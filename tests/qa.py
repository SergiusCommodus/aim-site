        await pg.click("button[data-v=Owned]"); await wait(pg, 150)
        ok(await pg.locator("tr[data-go]").count() == 1, "status filter works")
        await pg.click("button[data-v=All]")
        async with pg.expect_download() as dl:
            await pg.click("button[data-act=csv][data-v=opps]")
