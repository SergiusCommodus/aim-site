        ok(await pg.locator("text=Financing options").count() == 1, "financing options table shows")
        await pg.click("button[data-v=diligence]"); await wait(pg, 200)
        await pg.click("input[data-check='0']"); await wait(pg, 250)
        ok(await pg.is_checked("input[data-check='0']"), "checklist item stays checked after save")
        await pg.fill("#checkIn", "Call the county about permits"); await pg.press("#checkIn", "Enter"); await wait(pg, 200)
        ok(await pg.locator("text=Call the county about permits").count() == 1, "custom checklist item added")
        await pg.fill("#logIn", "Offer sent at $325,000"); await pg.press("#logIn", "Enter"); await wait(pg, 200)
        ok(await pg.locator(".timeline >> text=Offer sent at $325,000").count() == 1, "history note logged")
        await pg.select_option("#oppStatus", "Owned"); await wait(pg, 300)
        ok(await pg.locator("button[data-v=ownership]").count() == 1, "marking Owned adds the Ownership tab")
        await pg.click("button[data-v=ownership]"); await pg.click("button[data-act=add-actual]"); await wait(pg, 300)
        ok(await pg.locator("input[data-k=revenue]").count() == 1, "owned month logged")
        await pg.click("button[data-v=report]"); await wait(pg, 200)
        await pg.click("button[data-act=copy-report]"); await wait(pg, 300)
        clip = await pg.evaluate("navigator.clipboard.readText()")
