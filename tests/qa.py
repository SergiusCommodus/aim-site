        ok(await pg.locator(".modal").count() == 1, "score explanation opens")
        await pg.keyboard.press("Escape"); await wait(pg, 300)
        ok(await pg.locator(".modal").count() == 0, "Escape closes a dialog")
        ok(await pg.locator("text=Loan schedule").count() == 1, "loan schedule shows")
        await pg.click("button[data-act=all-years]"); await wait(pg, 150)
