        await pg.click("button[data-act='new-opp']"); await pg.click(".types label:has(input[value=str])")
        await pg.click(".modal button[type=submit]"); await wait(pg, 150)
        ok("Give the analysis a name" in await pg.inner_text(".modal"), "new analysis asks for a name")
        await pg.fill("#nName", "Smoky Mountain Cabin"); await pg.fill("#nLoc", "Gatlinburg, TN"); await pg.click(".modal button[type=submit]"); await wait(pg, 400)
        ok(await pg.input_value("#oppName") == "Smoky Mountain Cabin", "new analysis created and opened")
        sc0 = await pg.eval_on_selector("#results .dial text", "e=>e.textContent")
