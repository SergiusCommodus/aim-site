SHOTS = os.environ.get("AIM_QA_SHOTS", "/tmp/claude-0/shots")
fails, errs = [], []
def ok(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond: fails.append(msg)

async def wait(pg, ms=250): await pg.wait_for_timeout(ms)

