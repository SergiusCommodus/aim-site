        d0 = await pg.inner_text(".kpi.hero strong")
        await pg.fill("#pl-extra", "1000"); await pg.press("#pl-extra", "Tab"); await wait(pg, 300)
        d1 = await pg.inner_text(".kpi.hero strong")
        ok(d0 != d1, f"more extra payment moves the debt free date ({d0} to {d1})")
        await pg.click("button[data-act=plan-method][data-v=snowball]"); await wait(pg, 200)
        ok(await pg.locator("button[data-act=plan-method][data-v=snowball][aria-pressed=true]").count() == 1, "snowball method selects")
        ok("Credit card balance" in await pg.locator(".timeline li").first.inner_text(), "snowball pays the smallest balance first")
        await S("planner_debt")
        await pg.click("button[data-act=plan-tab][data-v=fi]"); await wait(pg, 900)
        y0 = await pg.locator(".kpi").nth(1).inner_text()
        await pg.fill("#pf-monthly", "5000"); await pg.press("#pf-monthly", "Tab"); await wait(pg, 300)
        y1 = await pg.locator(".kpi").nth(1).inner_text()
        ok(y0 != y1, "investing more changes the independence date")
        await pg.click("button[data-act=plan-reset]"); await wait(pg, 200)
        ok(await pg.locator(".kpi").nth(1).inner_text() == y0, "Use my numbers restores the defaults")
        await S("planner_fi")

        await pg.goto(B + "app.html#settings"); await wait(pg)
        await pg.fill("#s-coc", "12"); await pg.locator("#s-coc").press("Tab"); await wait(pg, 300)
        await pg.goto(B + "app.html#aimbot"); await wait(pg)
        await pg.fill("#botIn", "what should I offer"); await pg.press("#botIn", "Enter"); await wait(pg, 200)
        ok("12%" in await pg.locator(".msg.bot").last.inner_text(), "AIMBot uses the updated 12% target")
        await pg.click("button[data-act=ask][data-q='How do I pay off my debt?']"); await wait(pg, 200)
        ok("Avalanche" in await pg.locator(".msg.bot").last.inner_text(), "AIMBot answers debt questions")
        await pg.click("button[data-act=ask][data-q='When can I retire?']"); await wait(pg, 200)
        ok("independence number" in await pg.locator(".msg.bot").last.inner_text(), "AIMBot answers independence questions")

        # palette and shortcuts
        await pg.goto(B + "app.html#dashboard"); await wait(pg)
        await pg.keyboard.press("Control+k"); await wait(pg, 150)
        ok(await pg.locator("#palIn").count() == 1, "Ctrl K opens search")
        await pg.keyboard.type("gulf"); await wait(pg, 150); await pg.keyboard.press("Enter"); await wait(pg, 300)
        ok("opp-" in pg.url and await pg.input_value("#oppName") == "Gulf Breeze Condo", "search jumps to a deal")
        await pg.click("body", position={"x": 5, "y": 5}); await pg.keyboard.press("g"); await pg.keyboard.press("b"); await wait(pg, 250)
        ok(pg.url.endswith("#budget"), "g then b opens the budget")

        # reset demo
        await pg.goto(B + "app.html#settings"); await wait(pg)
        await pg.click("main button[data-act=ask-reset-demo]"); await pg.click("button[data-act=do-reset-demo]"); await wait(pg, 300)
        await pg.goto(B + "app.html#opportunities"); await wait(pg)
        ok(await pg.locator("tr[data-go]").count() == 5, "reset demo restores the sample portfolio")

        # ---------- get started and setup ----------
        await pg.goto(B + "demo.html"); await pg.click("#go"); await wait(pg, 150)
        ok(await pg.locator("[aria-invalid=true]").count() == 4, "get started form flags all 4 required fields")
        await pg.fill("#fname", "George"); await pg.fill("#lname", "Serafin"); await pg.fill("#email", "bad"); await pg.select_option("#role", index=2)
