        await pg.fill("#email", "george@example.com"); await pg.click("input[value='Business acquisitions']"); await pg.click("#go")
        await pg.wait_for_selector("#open")
        ok(await pg.locator("a[href='app.html#demo']").count() >= 1, "success offers the demo too")
        await pg.click("#open"); await wait(pg, 400)
        ok("step 1 of 5" in (await body()).lower(), "setup wizard opens")
        ok(await pg.input_value("#su-name") == "George", "setup prefills the first name")
        ok(await pg.is_checked("input[data-su-focus='Business acquisitions']"), "setup prefills interests")
        await pg.fill("#su-name", ""); await pg.click("#setupForm button[type=submit]"); await wait(pg, 150)
        ok("Enter your first name" in await body(), "setup requires a name")
        await pg.fill("#su-name", "George"); await pg.click("#setupForm button[type=submit]"); await wait(pg, 200)
        await pg.fill("#su-pay", "7200"); await pg.fill("#su-exp-housing", "2100"); await pg.fill("#su-exp-groceries", "600"); await wait(pg, 100)
        ok("$4,500" in await pg.inner_text("#suSum"), "setup shows live free cash flow")
        await pg.click("#setupForm button[type=submit]"); await wait(pg, 200)
        await pg.fill("#su-cash", "40000"); await pg.fill("#su-invest", "25000")
        await pg.locator("[data-sd][data-k=name]").first.fill("Car loan"); await pg.locator("[data-sd][data-k=balance]").first.fill("18000")
        await pg.locator("[data-sd][data-k=rate]").first.fill("6.5"); await pg.locator("[data-sd][data-k=min]").first.fill("390")
        await pg.click("button[data-act=su-add-debt]"); await wait(pg, 150)
        ok(await pg.input_value("[data-sd][data-k=balance] >> nth=0") == "18000", "adding a debt keeps typed values")
        await pg.click("#setupForm button[type=submit]"); await wait(pg, 200)
        await pg.click("button[data-act=su-preset][data-v=conservative]"); await wait(pg, 150)
        ok(await pg.input_value("#su-coc") == "10", "target preset fills the fields")
        await pg.click("#setupForm button[type=submit]"); await wait(pg, 900)
        rv = await body()
        ok("$47,000" in rv and "$4,500" in rv, "review shows net worth and free cash flow")
        await S("setup_review")
        await pg.click("input[data-su-first][value=rental]"); await pg.click("#setupForm button[type=submit]"); await wait(pg, 500)
        ok("opp-" in pg.url and await pg.input_value("#oppName") == "My first rental", "setup can start a first analysis")
