        ok("George" in await pg.inner_text("h1"), "live workspace greets by name")
        ok(await pg.locator(".ribbon").count() == 0, "live workspace has no demo ribbon")
        ok("3 of 5" in await body(), "setup completes three checklist steps")
        await pg.goto(B + "app.html#opportunities"); await wait(pg)
        ok(await pg.locator("tr[data-go]").count() == 1, "live workspace holds only its own deal")
        await pg.goto(B + "app.html#settings"); await wait(pg)
        ok(await pg.input_value("#s-coc") == "10", "live targets come from setup")
        await pg.click(".modesw button[data-v=demo]"); await wait(pg, 300)
        await pg.goto(B + "app.html#opportunities"); await wait(pg)
        ok(await pg.locator("tr[data-go]").count() == 5, "demo data is kept separate")
        await pg.click(".modesw button[data-v=live]"); await wait(pg, 300)
        ok("George" in await pg.inner_text("h1"), "switching back opens the live workspace")

        # share link import into live
        await pg.goto(share.replace("http://127.0.0.1:8766/", B)); await wait(pg, 400)
